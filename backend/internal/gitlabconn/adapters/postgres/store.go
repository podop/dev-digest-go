// Package postgres stores the GitLab connections (installation-wide, no workspace) with GORM and
// counts the repositories bound to them. Every statement gets its handle from pg.Conn, so it joins
// the transaction a use case opened through InTx. The token of a connection is not stored here: it
// lives in the secrets store (spec FR4). A repository is bound to a connection by its host key
// (repos.host = gitlab_connections.host, provider 'gitlab'), resolved at every read; there is no
// foreign key, so deleting a connection keeps its repositories (spec FR7, D26).
package postgres

import (
	"context"
	"fmt"

	"gorm.io/gorm"
	"gorm.io/gorm/clause"

	"dev-digest-go/backend/internal/gitlabconn/app"
	"dev-digest-go/backend/internal/gitlabconn/domain"
	pg "dev-digest-go/backend/internal/platform/postgres"
)

// Store is the Postgres store of the GitLab connections. It implements app.Store and
// app.RepoCounter.
type Store struct {
	db *gorm.DB
	tx *pg.Tx
}

var (
	_ app.Store       = (*Store)(nil)
	_ app.RepoCounter = (*Store)(nil)
)

// NewStore builds a Store on a GORM handle. The transaction runner is the same one a use case gets
// from pg.NewTx(db): a transaction opened with either is joined by the other.
func NewStore(db *gorm.DB) *Store { return &Store{db: db, tx: pg.NewTx(db)} }

// InTx runs fn in one transaction (see pg.Tx.InTx).
func (s *Store) InTx(ctx context.Context, fn func(ctx context.Context) error) error {
	return s.tx.InTx(ctx, fn)
}

// List returns every connection sorted by name, then host, in byte order (spec FR3).
func (s *Store) List(ctx context.Context) ([]domain.Connection, error) {
	var rows []connectionRow
	err := pg.Conn(ctx, s.db).Table(connectionsTable).Select(connectionColumns).
		Order(`name COLLATE "C", host COLLATE "C", id`).Scan(&rows).Error
	if err != nil {
		return nil, fmt.Errorf("select gitlab connections: %w", err)
	}
	out := make([]domain.Connection, 0, len(rows))
	for _, r := range rows {
		out = append(out, r.toDomain())
	}
	return out, nil
}

// Get returns one connection; domain.ErrNotFound when no connection has the id (a malformed id
// included).
func (s *Store) Get(ctx context.Context, id string) (domain.Connection, error) {
	if !validUUID(id) {
		return domain.Connection{}, domain.ErrNotFound
	}
	return s.get(ctx, "id = ?::uuid", id, nil)
}

// GetForUpdate is Get that locks the connection row FOR UPDATE until the transaction ends.
func (s *Store) GetForUpdate(ctx context.Context, id string) (domain.Connection, error) {
	if !validUUID(id) {
		return domain.Connection{}, domain.ErrNotFound
	}
	return s.get(ctx, "id = ?::uuid", id, &clause.Locking{Strength: clause.LockingStrengthUpdate})
}

// GetByHost returns the connection of a host key; domain.ErrNotFound when there is none.
func (s *Store) GetByHost(ctx context.Context, host string) (domain.Connection, error) {
	return s.get(ctx, "host = ?", host, nil)
}

// get reads one connection by a condition; a non-nil lock is applied to its row.
func (s *Store) get(ctx context.Context, cond, arg string, lock *clause.Locking) (domain.Connection, error) {
	var rows []connectionRow
	q := pg.Conn(ctx, s.db).Table(connectionsTable).Select(connectionColumns).Where(cond, arg)
	if lock != nil {
		q = q.Clauses(*lock)
	}
	if err := q.Scan(&rows).Error; err != nil {
		return domain.Connection{}, fmt.Errorf("select gitlab connection: %w", err)
	}
	if len(rows) == 0 {
		return domain.Connection{}, domain.ErrNotFound
	}
	return rows[0].toDomain(), nil
}

// Insert creates the connection. An empty c.ID is generated by the database; zero timestamps
// default to now(). Under a global lock that serializes the creates of
// the installation (a transaction-level advisory lock; connections belong to no workspace) it
// returns domain.ErrExists when the host key is taken, else domain.ErrLimit when limit connections
// exist already. A duplicate-key error from the insert itself (gitlab_connections_host_uq), which
// only a writer outside this method could cause, is ErrExists too. Called outside a transaction it
// opens one, so the lock covers the whole check-and-insert.
func (s *Store) Insert(ctx context.Context, c domain.Connection, limit int) error {
	return s.tx.InTx(ctx, func(ctx context.Context) error {
		conn := pg.Conn(ctx, s.db)
		// Raw SQL: an advisory lock has no builder form.
		if err := conn.Exec(`SELECT pg_advisory_xact_lock(hashtextextended(?, 0))`, lockKey).Error; err != nil {
			return fmt.Errorf("lock gitlab connections: %w", err)
		}
		var taken int64
		if err := conn.Table(connectionsTable).Where("host = ?", c.Host).Count(&taken).Error; err != nil {
			return fmt.Errorf("select gitlab connection host: %w", err)
		}
		if taken > 0 {
			return domain.ErrExists
		}
		var n int64
		if err := conn.Table(connectionsTable).Count(&n).Error; err != nil {
			return fmt.Errorf("count gitlab connections: %w", err)
		}
		if int(n) >= limit {
			return domain.ErrLimit
		}
		// The savepoint keeps the surrounding transaction usable if the insert fails on the key.
		return s.tx.Savepoint(ctx, func(ctx context.Context) error {
			// Raw SQL: the id and timestamps fall back to their column defaults when unset.
			err := pg.Conn(ctx, s.db).Exec(`INSERT INTO gitlab_connections (id, name, base_url, host, created_at, updated_at)
				VALUES (COALESCE(?::uuid, gen_random_uuid()), ?, ?, ?, COALESCE(?, now()), COALESCE(?, now()))`,
				nullIfEmpty(c.ID), c.Name, c.BaseURL, c.Host, nullTime(c.CreatedAt), nullTime(c.UpdatedAt)).Error
			if err != nil {
				if isUniqueViolation(err) {
					return domain.ErrExists
				}
				return fmt.Errorf("insert gitlab connection: %w", err)
			}
			return nil
		})
	})
}

// Replace overwrites the name, base URL and updated_at (zero: now()) of the connection. The id,
// the host key and created_at never change (spec FR5: repositories are bound by host); c.Host is
// not written. domain.ErrNotFound when the connection does not exist.
func (s *Store) Replace(ctx context.Context, c domain.Connection) error {
	if !validUUID(c.ID) {
		return domain.ErrNotFound
	}
	// Raw SQL: updated_at falls back to now() when unset.
	res := pg.Conn(ctx, s.db).Exec(`UPDATE gitlab_connections SET name = ?, base_url = ?, updated_at = COALESCE(?, now())
		WHERE id = ?::uuid`, c.Name, c.BaseURL, nullTime(c.UpdatedAt), c.ID)
	if res.Error != nil {
		return fmt.Errorf("update gitlab connection: %w", res.Error)
	}
	if res.RowsAffected == 0 {
		return domain.ErrNotFound
	}
	return nil
}

// Delete removes the connection. The repositories bound to its host key are not touched: they
// become "not connected" (spec FR7). domain.ErrNotFound when missing.
func (s *Store) Delete(ctx context.Context, id string) error {
	if !validUUID(id) {
		return domain.ErrNotFound
	}
	res := pg.Conn(ctx, s.db).Table(connectionsTable).Where("id = ?::uuid", id).Delete(&connectionRow{})
	if res.Error != nil {
		return fmt.Errorf("delete gitlab connection: %w", res.Error)
	}
	if res.RowsAffected == 0 {
		return domain.ErrNotFound
	}
	return nil
}

// CountBound returns, for each given host key, the number of GitLab repositories in all workspaces
// bound to it (provider 'gitlab', repos.host equal to the key; spec FR8). A host without
// repositories is absent from the map. Called with the ctx of InTx's fn it reads inside that
// transaction.
func (s *Store) CountBound(ctx context.Context, hosts []string) (map[string]int, error) {
	out := make(map[string]int, len(hosts))
	if len(hosts) == 0 {
		return out, nil
	}
	var rows []hostCountRow
	err := pg.Conn(ctx, s.db).Table(reposTable).Select("host, count(*) AS n").
		Where("provider = ? AND host IN ?", "gitlab", hosts).Group("host").Scan(&rows).Error
	if err != nil {
		return nil, fmt.Errorf("count gitlab repositories: %w", err)
	}
	for _, r := range rows {
		out[r.Host] = r.Count
	}
	return out, nil
}

// lockKey keys the advisory lock that serializes the creates (one global lock: connections belong
// to no workspace).
const lockKey = "gitlab_connections"
