// filePackages returns the repo's file_packages rows as sorted "path key" strings.
func (e *env) filePackages() []string {
	e.t.Helper()
	rows := e.scanStrings(`SELECT file_path || ' ' || package_key FROM file_packages WHERE repo_id = ?`, e.repo)
	slices.Sort(rows)
	return rows
}

// edges returns the repo's file_edges rows as sorted "from -> to" strings.
func (e *env) edges() []string {
	e.t.Helper()
	rows := e.scanStrings(`SELECT from_file || ' -> ' || to_file FROM file_edges WHERE repo_id = ?`, e.repo)
	slices.Sort(rows)
	return rows
}

// declFiles returns the sorted decl_file values ("NULL" for none) of the references to name in
// from.
func (e *env) declFiles(from, name string) []string {
	e.t.Helper()
	rows := e.scanStrings(`SELECT coalesce(decl_file, 'NULL') FROM "references" WHERE repo_id = ? AND from_path = ? AND to_symbol = ?`,
		e.repo, from, name)
	slices.Sort(rows)
	return rows
}

// AC1–AC4: a full index of the Go module indexes every file but the generated one, with its
// symbols, references, import edges and package keys.
func TestGo_FullIndex(t *testing.T) {
	e := newEnv(t, withFiles(goFixture()))
	e.mustFull()

	// AC1
	st := e.mustState()
	if st.Status != domain.StatusFull || st.FilesIndexed != 6 {
		t.Errorf("state = {%s files_indexed %d}, want {full 6}", st.Status, st.FilesIndexed)
	}
	if got := statInt(t, st, "totalCandidates"); got != 6 {
		t.Errorf("stats.totalCandidates = %d, want 6 (gen/x.pb.go not counted)", got)
	}
	if got := statInt(t, st, "filesSeen"); got != 6 {
		t.Errorf("stats.filesSeen = %d, want 6", got)
	}
	if degraded, ok := st.Stats["parseDegraded"].([]any); !ok || len(degraded) != 0 {
		t.Errorf("stats.parseDegraded = %#v, want an empty array", st.Stats["parseDegraded"])
	}
	for _, c := range []struct{ stat, table string }{
		{"symbolsWritten", "symbols"}, {"referencesWritten", `"references"`}, {"edgesWritten", "file_edges"},
		{"factsWritten", "file_facts"},
	} {
		if got, want := statInt(t, st, c.stat), e.count(c.table); got != want {
			t.Errorf("stats.%s = %d, rows in %s = %d, want equal", c.stat, got, c.table, want)
		}
	}
	for _, table := range []struct{ name, column string }{
		{"symbols", "path"}, {`"references"`, "from_path"}, {"file_facts", "file_path"}, {"file_packages", "file_path"},
		{"file_rank", "file_path"}, {"file_edges", "to_file"},
	} {
		if slices.ContainsFunc(e.paths(table.name, table.column), func(p string) bool { return strings.HasPrefix(p, "gen/") }) {
			t.Errorf("%s.%s holds gen/x.pb.go, want the generated file left out", table.name, table.column)
		}
	}

	// AC2: functions, methods with their receiver, struct → class, interface, other types; no
	// var or const; exported by the first letter.
	wantSymbols := []string{
		"internal/api/handler.go|GetX|method|17|20|true|func (h *Handler) GetX(c echo.Context) error",
		"internal/api/handler.go|Handler|class|12|14|true|type Handler struct",
		"internal/api/router.go|Register|function|6|8|true|func Register(e *echo.Echo, h *Handler)",
		"internal/api/util.go|clean|function|6|8|false|func clean(s string) string",
		"internal/svc/service.go|Doer|interface|11|13|true|type Doer interface",
		"internal/svc/service.go|Do|function|24|27|true|func Do(ctx context.Context) string",
		"internal/svc/service.go|Mode|type|16|16|true|type Mode string",
		"internal/svc/service.go|Name|method|30|32|true|func (s *Service) Name() string",
		"internal/svc/service.go|Service|class|6|8|true|type Service struct",
		"internal/svc/service_test.go|TestDo|function|8|12|true|func TestDo(t *testing.T)",
		"main.go|main|function|9|13|false|func main()",
	}
	gotSymbols := e.scanStrings(`SELECT path || '|' || name || '|' || kind || '|' || line::text || '|' || end_line::text || '|' ||
		exported::text || '|' || coalesce(signature, '') FROM symbols WHERE repo_id = ?`, e.repo)
	slices.Sort(gotSymbols)
	if diff := cmp.Diff(wantSymbols, gotSymbols); diff != "" {
		t.Errorf("symbols mismatch (-want +got):\n%s", diff)
	}

	// AC3: called names, selector fields, function values passed as arguments, composite literals.
	gotRefs := e.scanStrings(`SELECT from_path || ':' || to_symbol || ':' || line::text FROM "references" WHERE repo_id = ?`, e.repo)
	for _, want := range []string{
		"internal/api/handler.go:clean:19",  // called name
		"internal/api/handler.go:Do:18",     // selector field of a call
		"internal/api/router.go:GET:7",      // selector field of a call
		"internal/api/router.go:GetX:7",     // function value h.GetX passed as an argument
		"main.go:Handler:11",                // composite-literal type &api.Handler{}
		"main.go:Register:11",               // qualified call api.Register
		"internal/svc/service_test.go:Do:9", // call in the package's test
	} {
		if !slices.Contains(gotRefs, want) {
			t.Errorf("references lack %q, have %v", want, gotRefs)
		}
	}

	// AC4: internal imports end in the package's non-test files; standard-library and external
	// imports have no edge.
	wantEdges := []string{
		"internal/api/handler.go -> internal/svc/service.go",
		"main.go -> internal/api/handler.go",
		"main.go -> internal/api/router.go",
		"main.go -> internal/api/util.go",
	}
	if diff := cmp.Diff(wantEdges, e.edges()); diff != "" {
		t.Errorf("file_edges mismatch (-want +got):\n%s", diff)
	}
	if got := statInt(t, st, "edgesWritten"); got != len(wantEdges) {
		t.Errorf("stats.edgesWritten = %d, want %d", got, len(wantEdges))
	}
	if got := statInt(t, st, "symbolsWritten"); got != len(wantSymbols) {
		t.Errorf("stats.symbolsWritten = %d, want %d", got, len(wantSymbols))
	}
	if diff := cmp.Diff(goFilePackages, e.filePackages()); diff != "" {
		t.Errorf("file_packages mismatch (-want +got):\n%s", diff)
	}

	// The Go route of router.go is its only fact; the generated gRPC registration is not read.
	facts := e.scanStrings(`SELECT file_path || ' ' || endpoints::text || ' ' || crons::text FROM file_facts WHERE repo_id = ?`, e.repo)
	if diff := cmp.Diff([]string{`internal/api/router.go ["GET /x"] []`}, facts); diff != "" {
		t.Errorf("file_facts mismatch (-want +got):\n%s", diff)
	}
}

// AC6, AC7: a name declared once in another file of the caller's package resolves to that file;
// two declarations leave it unresolved; a reference resolved through an import edge keeps it.
func TestGo_ReferenceResolution(t *testing.T) {
	t.Run("AC1 fixture", func(t *testing.T) {
		e := newEnv(t, withFiles(goFixture()))
		e.mustFull()
		tests := []struct {
			name, from, symbol string
			want               []string
		}{
			{"unexported helper in another file of the package", "internal/api/handler.go", "clean", []string{"internal/api/util.go"}},
			{"package test calls the package", "internal/svc/service_test.go", "Do", []string{"internal/svc/service.go"}},
			{"method value of the package's handler", "internal/api/router.go", "GetX", []string{"internal/api/handler.go"}},
			{"call through the import edge", "internal/api/handler.go", "Do", []string{"internal/svc/service.go"}},
			{"external call stays unresolved", "internal/api/router.go", "GET", []string{"NULL"}},
		}
		for _, tc := range tests {
			t.Run(tc.name, func(t *testing.T) {
				if diff := cmp.Diff(tc.want, e.declFiles(tc.from, tc.symbol)); diff != "" {
					t.Errorf("decl_file of %s in %s mismatch (-want +got):\n%s", tc.symbol, tc.from, diff)
				}
			})
		}
	})

	t.Run("two declarations in the package and an import edge", func(t *testing.T) {
		files := goFixture()
		// Build-constrained files declare home twice; home_linux.go also declares a Do of
		// internal/api, which the import edge of handler.go to internal/svc must not lose to.
		files["internal/api/home_linux.go"] = "package api\n\nfunc home() string {\n\treturn \"/home\"\n}\n\nfunc Do() string {\n\treturn \"\"\n}\n"
		files["internal/api/home_windows.go"] = "package api\n\nfunc home() string {\n\treturn \"C:\\\\Users\"\n}\n"
		files["internal/api/paths.go"] = "package api\n\nfunc configDir() string {\n\treturn home() + \"/.config\"\n}\n"
		e := newEnv(t, withFiles(files))
		e.mustFull()
		if diff := cmp.Diff([]string{"NULL"}, e.declFiles("internal/api/paths.go", "home")); diff != "" {
			t.Errorf("decl_file of home declared in two files of the package mismatch (-want +got):\n%s", diff)
		}
		if diff := cmp.Diff([]string{"internal/svc/service.go"}, e.declFiles("internal/api/handler.go", "Do")); diff != "" {
			t.Errorf("decl_file of Do resolved through the import edge mismatch (-want +got):\n%s", diff)
		}
	})
}

// AC9: the blast radius of the Go module from the persistent index.
func TestGo_BlastRadius(t *testing.T) {
	e := newEnv(t, withFiles(goFixture()))
	e.mustFull()

	callerSet := func(got domain.BlastResult) map[string]string {
		out := map[string]string{}
		for _, c := range got.Callers {
			out[c.File] = c.Symbol + " via " + c.ViaSymbol
		}
		return out
	}

	t.Run("service changed", func(t *testing.T) {
		got := e.blast(e.reader, "internal/svc/service.go")
		if got.Degraded || got.Reason != "" {
			t.Errorf("BlastRadius(service.go) = degraded %v reason %q, want complete", got.Degraded, got.Reason)
		}
		if !slices.Contains(got.ChangedSymbols, domain.BlastSymbol{File: "internal/svc/service.go", Name: "Do", Kind: "function"}) {
			t.Errorf("BlastRadius(service.go) changed symbols = %+v, want Do among them", got.ChangedSymbols)
		}
		want := map[string]string{
			"internal/api/handler.go":      "GetX via Do",
			"internal/svc/service_test.go": "TestDo via Do",
		}
		if diff := cmp.Diff(want, callerSet(got)); diff != "" {
			t.Errorf("BlastRadius(service.go) callers mismatch (-want +got):\n%s", diff)
		}
	})

	t.Run("handler changed", func(t *testing.T) {
		got := e.blast(e.reader, "internal/api/handler.go")
		if got.Degraded || got.Reason != "" {
			t.Errorf("BlastRadius(handler.go) = degraded %v reason %q, want complete", got.Degraded, got.Reason)
		}
		callers := callerSet(got)
		if callers["internal/api/router.go"] != "Register via GetX" {
			t.Errorf("BlastRadius(handler.go) callers = %v, want internal/api/router.go as Register via GetX", callers)
		}
		want := domain.BlastFacts{Endpoints: []string{"GET /x"}, Crons: []string{}}
		if diff := cmp.Diff(want, got.FactsByFile["internal/api/router.go"]); diff != "" {
			t.Errorf("BlastRadius(handler.go) facts of router.go mismatch (-want +got):\n%s", diff)
		}
	})
}

// Review Focus 4: a TypeScript repo that adds a go.mod and then Go files indexes the Go files on
// the incremental slice, at the same indexer version, with their package rows.
func TestGo_IncrementalAddsGoFiles(t *testing.T) {
	e := newEnv(t)
	e.mustFull()
	if got := e.count("file_packages"); got != 0 {
		t.Fatalf("file_packages rows of the TypeScript index = %d, want 0", got)
	}

	// The module file alone: a changed go.mod runs the full index (AC16), with nothing to add.
	e.git.Commit(map[string]string{"go.mod": goFixture()["go.mod"]})
	e.mustIncremental()

	head := e.git.Commit(goFixtureSources())
	e.mustIncremental()
	st := e.mustState()
	if !isIncremental(st) || st.Status != domain.StatusFull || st.IndexerVersion != domain.IndexerVersion || st.LastIndexedSHA != head {
		t.Fatalf("state = {%s incremental %v v%d %q}, want a clean incremental slice at v%d %q",
			st.Status, isIncremental(st), st.IndexerVersion, st.LastIndexedSHA, domain.IndexerVersion, head)
	}
	names := e.symbolNames()
	for _, want := range []string{"internal/api/handler.go:GetX", "internal/svc/service.go:Do", "main.go:main", "src/core.ts:core"} {
		if !slices.Contains(names, want) {
			t.Errorf("symbols lack %s after the slice", want)
		}
	}
	if diff := cmp.Diff(goFilePackages, e.filePackages()); diff != "" {
		t.Errorf("file_packages after the slice mismatch (-want +got):\n%s", diff)
	}
	if !slices.Contains(e.edges(), "internal/api/handler.go -> internal/svc/service.go") {
		t.Errorf("file_edges = %v, want internal/api/handler.go -> internal/svc/service.go", e.edges())
	}
	if diff := cmp.Diff([]string{"internal/api/util.go"}, e.declFiles("internal/api/handler.go", "clean")); diff != "" {
		t.Errorf("decl_file of clean after the slice mismatch (-want +got):\n%s", diff)
	}

	// The slice equals a full index of the same commit.
	slice, slicePkgs := e.content(), e.dump("file_packages", "repo_id")
	e.mustFull()
	full, fullPkgs := e.content(), e.dump("file_packages", "repo_id")
	for _, table := range []string{"symbols", `"references"`, "file_edges", "file_rank", "file_facts"} {
		if diff := cmp.Diff(full[table], slice[table]); diff != "" {
			t.Errorf("%s after the slice differs from a full index (-full +slice):\n%s", table, diff)
		}
	}
	if diff := cmp.Diff(fullPkgs, slicePkgs); diff != "" {
		t.Errorf("file_packages after the slice differs from a full index (-full +slice):\n%s", diff)
	}
}

// AC16: a commit that changes only a go.mod, at the root or nested, runs a full index.
func TestGo_GoModChangeRunsFull(t *testing.T) {
	tests := []struct {
		name  string
		write map[string]string
	}{
		{"root go.mod changed", map[string]string{"go.mod": "module example.com/r\n\ngo 1.23\n"}},
		{"nested go.mod added", map[string]string{"tools/go.mod": "module example.com/r/tools\n\ngo 1.22\n"}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			e := newEnv(t, withFiles(goFixture()))
			e.mustFull()
			// The state row keeps the stats of the first full index, so the stats alone cannot tell
			// a second full index from a run that only advances the sha (go.mod is not a source
			// file): with the symbols gone, only a full index brings them back.
			e.exec(`DELETE FROM symbols WHERE repo_id = ?`, e.repo)
			head := e.git.Commit(tc.write)
			res := e.mustIncremental()

			if res.Reason != "" || res.FilesIndexed != 6 {
				t.Errorf("Incremental() = {reason %q files %d}, want a plain full index of 6 files", res.Reason, res.FilesIndexed)
			}
			if got := e.count("symbols"); got != 11 {
				t.Errorf("symbols rows = %d, want the 11 rows of a full index", got)
			}
			st := e.mustState()
			if isIncremental(st) || st.Status != domain.StatusFull || st.LastIndexedSHA != head || st.FilesIndexed != 6 {
				t.Errorf("state = {%s incremental %v %q files %d}, want a full index of %q with 6 files",
					st.Status, isIncremental(st), st.LastIndexedSHA, st.FilesIndexed, head)
			}
			if diff := cmp.Diff(fullStatsKeys, slices.Sorted(maps.Keys(st.Stats))); diff != "" {
				t.Errorf("stats keys mismatch, want the full-index keys (-want +got):\n%s", diff)
			}
		})
	}
}

// AC21: the caller scan of a Go module does not return callers from vendor/.
func TestGo_CallerScanSkipsVendor(t *testing.T) {
	files := goFixture()
	files["vendor/x/x.go"] = "package x\n\nimport \"example.com/r/internal/svc\"\n\nfunc UseDo() string {\n\treturn svc.Do(nil)\n}\n"
	e := newEnv(t, withFiles(files))
	r, log := e.callerReader(0)

	got, err := r.CallerSignatures(t.Context(), e.repo, []string{"internal/svc/service.go"}, 10)
	if err != nil {
		t.Fatalf("CallerSignatures(service.go) error = %v", err)
	}
	want := []domain.CallerSignature{
		{File: "internal/api/handler.go", Symbol: "GetX", Signature: "func (h *Handler) GetX(c echo.Context) error"},
		{File: "internal/svc/service_test.go", Symbol: "TestDo", Signature: "func TestDo(t *testing.T)"},
	}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("CallerSignatures(service.go) mismatch (-want +got):\n%s", diff)
	}
	for _, p := range log.paths {
		if strings.HasPrefix(p, "vendor/") {
			t.Errorf("the caller scan opened %q, want nothing under vendor/", p)
		}
	}
}
