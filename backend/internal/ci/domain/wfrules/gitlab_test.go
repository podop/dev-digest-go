// The corpus in testdata/gitlab holds one job file per file; the part of the name before "--" is
// the expected rule ("ok" = passes). Files with "custom" in the name are checked against a
// custom-provider export of MY_GW with two headers.
func TestCheckGitLab_Corpus(t *testing.T) {
	files, err := filepath.Glob("testdata/gitlab/*.yml")
	if err != nil || len(files) == 0 {
		t.Fatalf("Glob(testdata/gitlab/*.yml) = %v, %v, want files", files, err)
	}
	for _, f := range files {
		t.Run(filepath.Base(f), func(t *testing.T) {
			data, err := os.ReadFile(f)
			if err != nil {
				t.Fatalf("ReadFile(%s): %v", f, err)
			}
			want, _, _ := strings.Cut(filepath.Base(f), "--")
			rules := glPlain
			if strings.Contains(f, "custom") {
				rules = glCustom
			}
			got := wfrules.CheckGitLab(string(data), rules)
			wantRule := wfrules.Rule(want)
			if want == "ok" {
				wantRule = ""
			}
			if w := (wfrules.Result{OK: wantRule == "", Rule: wantRule}); got != w {
				t.Errorf("CheckGitLab(%s) = %+v, want %+v", filepath.Base(f), got, w)
			}
		})
	}
}

func FuzzCheckGitLab(f *testing.F) {
	f.Add(glJob, "", 0)
	f.Add(glCustomJob(), "MY_GW", 2)
	f.Add("a: &a [*a]", "", 0)
	f.Add("--- a\n--- b\n", "X", 1)
	f.Add("devdigest-review-test: !!set {a}", "", 0)
	f.Add(strings.Replace(glJob, "  script:\n", "  script:\n    - echo ${x:-$$%a%$env:b}\n", 1), "", 0)
	if files, err := filepath.Glob("testdata/gitlab/*.yml"); err == nil {
		for _, name := range files {
			if data, err := os.ReadFile(name); err == nil {
				f.Add(string(data), "MY_GW", 2)
			}
		}
	}
	valid := map[wfrules.Rule]bool{
		wfrules.InvalidYAML: true, wfrules.Structure: true, wfrules.Include: true, wfrules.ForbiddenTrigger: true,
		wfrules.UnpinnedImage: true, wfrules.Variables: true, wfrules.UntrustedVariable: true,
	}
	f.Fuzz(func(t *testing.T, text, env string, headers int) {
		start := time.Now()
		got := wfrules.CheckGitLab(text, wfrules.GitLabRules{Slug: "test", CustomEnv: env, HeaderCount: headers})
		if elapsed := time.Since(start); elapsed > time.Second {
			t.Errorf("CheckGitLab(%q) took %v, want a bounded run", text, elapsed)
		}
		if got.OK != (got.Rule == "") || (!got.OK && !valid[got.Rule]) {
			t.Errorf("CheckGitLab(%q) = %+v, want OK with no rule or a known rule", text, got)
		}
	})
}

