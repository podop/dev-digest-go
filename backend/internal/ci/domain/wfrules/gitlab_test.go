// glEdit replaces the first occurrence of old in glJob; a missing old is a bug in the test.
func glEdit(t testing.TB, old, replacement string) string {
	t.Helper()
	if !strings.Contains(glJob, old) {
		t.Fatalf("test bug: %q not in the generated job file", old)
	}
	return strings.Replace(glJob, old, replacement, 1)
}

// inJob indents top-level YAML lines to the variables of the job (the first line follows the
// caller's own indent), so that anchors and aliases are part of a job that passes `structure`.
func inJob(lines string) string {
	return strings.ReplaceAll(strings.TrimSuffix(lines, "\n"), "\n", "\n    ") + "\n"
}

func glCustomJob() string { return strings.Replace(glJob, glVarsEnd, glVarsEnd+glCustomVars, 1) }

