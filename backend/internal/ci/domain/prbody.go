package domain

import "strings"

// BuildPRBody is the body of the export pull request (spec 7.6.7): the files, the secret to add
// (name only), the check name and the runner paragraph with its SHA-256 and build id (D6008).
// paths are listed in the given order.
func BuildPRBody(slug string, paths []string, runnerSHA256, buildID string) string {
	files := make([]string, len(paths))
	for i, p := range paths {
		files[i] = "- `" + p + "`"
	}
	return strings.Join([]string{
		"Adds the DevDigest review agent `" + slug + "` to this repository's GitHub Actions.",
		"",
		"### Files",
		strings.Join(files, "\n"),
		"",
		"### Before merging",
		"1. Add the repository Actions secret `OPENROUTER_API_KEY` (Settings > Secrets and variables > Actions).",
		"   This PR triggers the review workflow on itself, so its check stays red until the secret exists.",
		"2. Merge this PR.",
		"3. To block merges on CRITICAL findings, add the status check `" + CheckName(slug) + "` as required in the branch protection of the default branch.",
		"",
		"### Runner",
		"`" + RunnerPath + "` is the DevDigest CI runner (linux/amd64), built from DevDigest source `" + buildID +
			"`. SHA-256 of the decoded binary: `" + runnerSHA256 + "`. The workflow checks it before running.",
		"",
		"Branch: `" + Branch + "`. Generated by DevDigest.",
	}, "\n")
}
