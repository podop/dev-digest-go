package domain

import "strings"

// BuildPRBody is the body of the export pull request of an openrouter agent (spec 7.6.7): the
// files, the secret to add (name only), the check name and the runner paragraph with its SHA-256
// and build id (D6008). paths are listed in the given order.
func BuildPRBody(slug string, paths []string, runnerSHA256, buildID string) string {
	return BuildPRBodyFor(slug, paths, runnerSHA256, buildID, []string{SecretOpenRouter}, nil)
}

// BuildPRBodyFor is BuildPRBody for any provider: step 1 of "Before merging" names each secret
// and variable to add (FR29, FR35), e.g. "1. Add the repository Actions secret `A` (Settings >
// Secrets and variables > Actions)." for one secret, "secrets `A`, `B`" for several and "... and
// the variable `V`" (or "variables") after them. With one secret and no variable the body equals
// BuildPRBody's.
func BuildPRBodyFor(slug string, paths []string, runnerSHA256, buildID string, secrets, variables []string) string {
	files := make([]string, len(paths))
	for i, p := range paths {
		files[i] = "- `" + p + "`"
	}
	return strings.Join([]string{
		"Adds the DevDigest review agent `" + slug + "` to this repository's GitHub Actions.",
		"",
		"### Files",
		strings.Join(files, "\n"),
		"",
		"### Before merging",
		"1. Add the repository Actions " + requiredItems(secrets, variables) + " (Settings > Secrets and variables > Actions).",
		"   This PR triggers the review workflow on itself, so its check stays red until the secret exists.",
		"2. Merge this PR.",
		"3. To block merges on CRITICAL findings, add the status check `" + CheckName(slug) + "` as required in the branch protection of the default branch.",
		"",
		"### Runner",
		"`" + RunnerPath + "` is the DevDigest CI runner (linux/amd64), built from DevDigest source `" + buildID +
			"`. SHA-256 of the decoded binary: `" + runnerSHA256 + "`. The workflow checks it before running.",
		"",
		"Branch: `" + Branch + "`. Generated by DevDigest.",
	}, "\n")
}

// requiredItems words the things step 1 asks for: "secret `A`", "secrets `A`, `B`", "secret `A`
// and the variable `V`", "variable `V`".
func requiredItems(secrets, variables []string) string {
	quote := func(names []string) string {
		q := make([]string, len(names))
		for i, n := range names {
			q[i] = "`" + n + "`"
		}
		return strings.Join(q, ", ")
	}
	plural := func(noun string, names []string) string {
		if len(names) == 1 {
			return noun + " " + quote(names)
		}
		return noun + "s " + quote(names)
	}
	var parts []string
	if len(secrets) > 0 {
		parts = append(parts, plural("secret", secrets))
	}
	if len(variables) > 0 {
		v := plural("variable", variables)
		if len(secrets) > 0 {
			v = "the " + v
		}
		parts = append(parts, v)
	}
	return strings.Join(parts, " and ")
}
