package domain

import (
	"strconv"
	"strings"
)

// RootConfig says what the export does about the project's root CI configuration (spec 7.1
// root_config, FR5, FR11).
type RootConfig string

// The root_config values.
const (
	// RootConfigCreate lists the root include file `.gitlab-ci.yml` (the project has none).
	RootConfigCreate RootConfig = "create"
	// RootConfigKeepExisting leaves the project's `.gitlab-ci.yml`; the user adds the include.
	RootConfigKeepExisting RootConfig = "keep_existing"
	// RootConfigCustomPath is a project whose ci_config_path is neither empty nor `.gitlab-ci.yml`:
	// no root file is written and the snippet names that path.
	RootConfigCustomPath RootConfig = "custom_path"
)

// The static warnings of an existing root configuration (EC14, EC15, SCR3). They are not derived
// from the configuration (it is never parsed): they are printed whenever the user has to add the
// include by hand.
const (
	WarnWorkflowRules = "If your workflow:rules exclude merge request pipelines, the review job cannot run"
	WarnStagesTest    = "Your stages must include test, or change the job's stage"
)

// MRDescInput are the values of the open_pr merge request description (spec 7.4).
type MRDescInput struct {
	Slug string
	// Paths are the committed or kept files, in file order.
	Paths []string
	// RunnerSHA256 and BuildID are the runner paragraph's facts, as in the GitHub body (D6008).
	RunnerSHA256, BuildID string
	// Secrets are the CI/CD variables to add as masked, unprotected variables: the output of
	// GitLabRequiredSecrets. The GitLabTokenVariable item gets its explanation.
	Secrets []string
	// Variables are the visible variables to add (RequiredVariables): the gateway base URL.
	Variables []string
	// RootConfig decides whether the include step is shown (every value but RootConfigCreate).
	RootConfig RootConfig
	// ConfigPath is the root configuration the include goes into; empty means `.gitlab-ci.yml`.
	ConfigPath string
	// TriggersNote is the FR4 note (TriggersNote) or "".
	TriggersNote string
}

// BuildMRDescription is the description of the export merge request (spec 7.4, FR12). Step 1
// names each variable to add (names only, NFR4), step 2 (the include snippet with the EC14 and
// EC15 warnings) appears only when the root configuration is not created by this export, and the
// steps are numbered in the order they appear. The FR4 note, when given, follows the last step.
func BuildMRDescription(in MRDescInput) string {
	files := make([]string, len(in.Paths))
	for i, p := range in.Paths {
		files[i] = "- `" + inlineCode(p) + "`"
	}
	var steps [][]string
	if step := variablesStep(in.Secrets, in.Variables); step != nil {
		steps = append(steps, step)
	}
	if in.RootConfig != RootConfigCreate {
		path := inlineCode(in.ConfigPath)
		if path == "" {
			path = GitLabRootConfigPath
		}
		steps = append(steps, []string{
			"Add this to `" + path + "`:",
			"   ```yaml",
			"   include:",
			"     - local: " + GitLabJobPath(in.Slug),
			"   ```",
			"   " + WarnWorkflowRules + ".",
			"   " + WarnStagesTest + ".",
		})
	}
	steps = append(steps,
		[]string{"Merge this merge request."},
		[]string{`To block merges on blockers, enable "Pipelines must succeed" (Settings > Merge requests > Merge checks).`},
	)

	lines := []string{
		"Adds the DevDigest review agent `" + in.Slug + "` to this project's GitLab CI.",
		"",
		"### Files",
		strings.Join(files, "\n"),
		"",
		"### Before merging",
	}
	for i, step := range steps {
		step[0] = strconv.Itoa(i+1) + ". " + step[0]
		lines = append(lines, step...)
	}
	if in.TriggersNote != "" {
		lines = append(lines, in.TriggersNote+".")
	}
	lines = append(lines,
		"",
		"### Runner",
		"`"+RunnerPath+"` is the DevDigest CI runner (linux/amd64), built from DevDigest source `"+in.BuildID+
			"`. SHA-256 of the decoded binary: `"+in.RunnerSHA256+"`. The job checks it before running.",
		"",
		"Branch: `"+Branch+"`. Generated by DevDigest.",
	)
	return strings.Join(lines, "\n")
}

// variablesStep is step 1 of "Before merging": the masked, unprotected variables (with the token
// explained), then the visible ones. It is nil when there is nothing to add.
func variablesStep(secrets, variables []string) []string {
	var lines []string
	if len(secrets) > 0 {
		lines = append(lines,
			"Add these CI/CD variables (Settings > CI/CD > Variables), each **masked** and **not protected**",
			"   (merge request pipelines cannot read protected variables):",
		)
		for _, s := range secrets {
			if s == GitLabTokenVariable {
				lines = append(lines,
					"   - `"+GitLabTokenVariable+"` — an access token with the `api` scope that DevDigest posts as",
					"     (a project access token with the Reporter role is recommended; on gitlab.com project access tokens need",
					"     Premium or Ultimate, otherwise use a personal access token of a dedicated user).",
				)
				continue
			}
			lines = append(lines, "   - `"+inlineCode(s)+"`")
		}
	}
	if len(variables) > 0 {
		quoted := make([]string, len(variables))
		for i, v := range variables {
			quoted[i] = "`" + inlineCode(v) + "`"
		}
		noun := "a visible variable"
		if len(variables) > 1 {
			noun = "visible variables"
		}
		if len(secrets) > 0 {
			lines = append(lines, "   And as "+noun+": "+strings.Join(quoted, ", ")+" = the gateway base URL.")
		} else {
			lines = append(lines, "Add "+noun+" (Settings > CI/CD > Variables): "+strings.Join(quoted, ", ")+" = the gateway base URL.")
		}
	}
	if len(lines) == 0 {
		return nil
	}
	return append(lines, "   This merge request runs the review job on itself, so its pipeline fails until the variables exist.")
}

// inlineCode makes s safe to put between backticks on one line: a backtick or a line break (a
// project's ci_config_path is user-controlled on GitLab) would end the code span or the list item.
func inlineCode(s string) string {
	return strings.Map(func(r rune) rune {
		if r == '`' || r == '\n' || r == '\r' {
			return -1
		}
		return r
	}, s)
}
