// The GitLab CI export target (GitLab C, FR1, FR2) and the source of the runs it ingests.
const (
	// TargetGitLabCI is the CI target of a GitLab repository (the wire value of CiTarget).
	TargetGitLabCI = "gitlab_ci"
	// RunSourceGitLab is ci_runs.source of an ingested GitLab job.
	RunSourceGitLab = "gitlab_ci"
)

// Names and locations of the GitLab export (spec 7.3).
const (
	// GitLabJobsDir holds the generated job files.
	GitLabJobsDir = ".gitlab/devdigest"
	// GitLabRootConfigPath is the root CI configuration the include snippet goes into (FR15).
	GitLabRootConfigPath = ".gitlab-ci.yml"
	// GitLabRunnerTag is the one tag of the Self-managed runner mode (FR9, D20).
	GitLabRunnerTag = "devdigest"
	// GitLabTokenVariable is the CI/CD variable that holds the token the runner posts with
	// (spec 7.4, 7.5). It is required whenever post_as is not none.
	GitLabTokenVariable = "DEVDIGEST_GITLAB_TOKEN"
)

// JobImage is the one public image every GitLab job file runs in (FR8, D19, SCR9): the official
// buildpack-deps -scm variant of Debian stable (it has sh, git, base64, gzip, sha256sum and CA
// certificates) pinned by the digest of its linux/amd64 manifest. It changes only with a
// DevDigest code change.
//
// The digest is the linux/amd64 manifest of buildpack-deps:trixie-scm as published on 2026-10-21
// (`docker buildx imagetools inspect buildpack-deps:trixie-scm`, read 2026-10-27).
const (
	jobImageName   = "buildpack-deps:trixie-scm"
	jobImageDigest = "57c2de9a151180bf9ba8eea8bbebf8c546ccaa629f4fec8ea9b18330226af31b"
	JobImage       = jobImageName + "@sha256:" + jobImageDigest
)

// MRRule is the job rule of the generated file: the job runs in merge request pipelines of the
// project itself, never for a fork (FR7, FR14 rule 3).
const MRRule = `$CI_PIPELINE_SOURCE == "merge_request_event" && $CI_MERGE_REQUEST_SOURCE_PROJECT_ID == $CI_MERGE_REQUEST_PROJECT_ID`

// GitLabJobName is the name of the one job of a job file (FR7, FR14 rule 1).
func GitLabJobName(slug string) string { return "devdigest-review-" + slug }

// GitLabJobPath is the repository path of an agent's job file (FR6).
func GitLabJobPath(slug string) string { return GitLabJobsDir + "/review-" + slug + ".yml" }

// IncludeSnippet is the text a root CI configuration needs to include the job file (spec 7.1
// include_snippet, FR15).
func IncludeSnippet(slug string) string {
	return "include:\n  - local: " + GitLabJobPath(slug) + "\n"
}

// BuildRootInclude is the root include file `.gitlab-ci.yml`, generated only when the project has
// none (FR15, spec 7.3). It holds the one include entry and nothing else.
func BuildRootInclude(slug string) string {
	return "# Added by DevDigest. Add your own jobs below or in other included files.\n" + IncludeSnippet(slug)
}

// GitLabJobOptions are the values interpolated into the generated job file.
type GitLabJobOptions struct {
	Slug   string
	PostAs PostAs
	// Provider is the agent's provider: a built-in or a well-formed custom id. Empty means
	// openrouter. Only a custom provider adds variables to the job (FR10).
	Provider string
	// Runner picks the tag (FR9); empty means GitHubHosted ("GitLab shared runners").
	Runner Runner
	// HeaderCount is the number of extra headers of a custom provider (0 to MaxExtraHeaders): one
	// DEVDIGEST_LLM_HEADER_<n> line each (FR10). It is ignored for a built-in provider.
	HeaderCount int
}

// gitLabJobTemplate is the text of spec 7.3 with @@NAME@@ placeholders. The values are checked
// before they are put in, so nothing user-controlled reaches the YAML (NFR4). Slot lines carry
// their own newline, so an empty slot leaves no blank line.
const gitLabJobTemplate = `# @@CHECK@@ — generated by DevDigest; included from the root CI configuration.
@@JOB@@:
  stage: test
  image:
    name: @@IMAGE@@
    entrypoint: [""]
@@TAGS@@  inherit:
    default: false
    variables: false
  rules:
    - if: @@RULE@@
  interruptible: true
  variables:
    GIT_DEPTH: "0"
    DEVDIGEST_PLATFORM: gitlab_ci
    DEVDIGEST_AGENT: @@SLUG@@
    DEVDIGEST_POST_AS: @@POST_AS@@
@@PROVIDER_VARS@@  script:
    - mkdir -p "/tmp/devdigest-$CI_JOB_ID"
    - base64 -d "$CI_PROJECT_DIR/@@RUNNER_PATH@@" > "/tmp/devdigest-$CI_JOB_ID/devdigest-runner.gz"
    - gzip -dc "/tmp/devdigest-$CI_JOB_ID/devdigest-runner.gz" > "/tmp/devdigest-$CI_JOB_ID/@@RUNNER_NAME@@"
    - cd "/tmp/devdigest-$CI_JOB_ID" && sha256sum -c "$CI_PROJECT_DIR/@@SUM_PATH@@"
    - chmod +x "/tmp/devdigest-$CI_JOB_ID/@@RUNNER_NAME@@"
    - cd "$CI_PROJECT_DIR" && "/tmp/devdigest-$CI_JOB_ID/@@RUNNER_NAME@@"
  artifacts:
    when: always
    name: @@ARTIFACT@@
    paths:
      - @@RESULT_FILE@@
    expire_in: 30 days
`

// gitLabProviderVars are the job variables lines (4-space indent, each ending in a newline) that
// map a custom provider's CI/CD variables to the names the runner reads (FR10). A built-in
// provider adds nothing: GitLab exports project variables to the job as they are. An empty
// provider is openrouter; false for an invalid provider or header count.
func gitLabProviderVars(provider string, headerCount int) (string, bool) {
	const indent = "    "
	if provider == "" {
		provider = ProviderOpenRouter
	}
	if _, ok := builtinSecret(provider); ok {
		return "", true
	}
	slug, ok := CustomSlug(provider)
	if !ok || headerCount < 0 || headerCount > MaxExtraHeaders {
		return "", false
	}
	env, _ := EnvName(slug)
	var b strings.Builder
	b.WriteString(indent + "DEVDIGEST_LLM_BASE_URL: $" + BaseURLVariable(env) + "\n")
	b.WriteString(indent + "DEVDIGEST_LLM_API_KEY: $" + APIKeySecret(env) + "\n")
	for n := 1; n <= headerCount; n++ {
		b.WriteString(indent + "DEVDIGEST_LLM_HEADER_" + strconv.Itoa(n) + ": $" + HeaderSecret(env, n) + "\n")
	}
	return b.String(), true
}

// BuildGitLabJob generates the hardened per-agent job file (spec 7.3, FR7). It decodes the
// committed runner, verifies its checksum and runs it. The result passes the GitLab rule
// checker for every provider, runner mode and post_as (NFR4). ErrInvalidWorkflowOptions is
// returned for a slug that does not match the slug shape, an unknown post_as, runner or provider,
// or a header count outside 0 to MaxExtraHeaders.
func BuildGitLabJob(o GitLabJobOptions) (string, error) {
	if !ValidSlug(o.Slug) {
		return "", fmt.Errorf("%w: slug", ErrInvalidWorkflowOptions)
	}
	if !ValidPostAs(o.PostAs) {
		return "", fmt.Errorf("%w: post_as", ErrInvalidWorkflowOptions)
	}
	if !o.Runner.Valid() {
		return "", fmt.Errorf("%w: runner", ErrInvalidWorkflowOptions)
	}
	providerVars, ok := gitLabProviderVars(o.Provider, o.HeaderCount)
	if !ok {
		return "", fmt.Errorf("%w: provider", ErrInvalidWorkflowOptions)
	}
	tags := ""
	if o.Runner == RunnerSelfHosted {
		tags = "  tags: [" + GitLabRunnerTag + "]\n"
	}
	return strings.NewReplacer(
		"@@CHECK@@", CheckName(o.Slug),
		"@@JOB@@", GitLabJobName(o.Slug),
		"@@IMAGE@@", JobImage,
		"@@TAGS@@", tags,
		"@@RULE@@", MRRule,
		"@@SLUG@@", o.Slug,
		"@@POST_AS@@", string(o.PostAs),
		"@@PROVIDER_VARS@@", providerVars,
		"@@RUNNER_PATH@@", RunnerPath,
		"@@RUNNER_NAME@@", RunnerBinaryName,
		"@@SUM_PATH@@", RunnerSumPath,
		"@@ARTIFACT@@", ArtifactName(o.Slug),
		"@@RESULT_FILE@@", ResultFileName,
	).Replace(gitLabJobTemplate), nil
}

// GitLabRequiredSecrets are the CI/CD variables the user must add as masked, unprotected
// variables before the job works (spec 7.1 required_secrets, FR10): the provider's secret names
// (see RequiredSecrets) followed by DEVDIGEST_GITLAB_TOKEN unless postAs is none. It is nil for
// an invalid provider and never nil otherwise.
func GitLabRequiredSecrets(provider string, keyConfigured bool, headerCount int, postAs PostAs) []string {
	if provider == "" {
		provider = ProviderOpenRouter
	}
	secrets := RequiredSecrets(provider, keyConfigured, headerCount)
	if secrets == nil {
		return nil
	}
	if postAs != PostAsNone {
		secrets = append(secrets, GitLabTokenVariable)
	}
	return secrets
}

// TriggersNoteText is the answer to triggers that GitLab cannot honour (FR4).
const TriggersNoteText = "GitLab runs merge request pipelines on every push; trigger choices do not apply"

// TriggersNote is the FR4 note for the requested triggers: a GitLab merge request pipeline runs on
// creation and on every push, which covers opened, synchronize and reopened, so the note is
// given (non-empty) when the requested triggers differ from all three, and "" otherwise. An empty
// list means the default, all three. The caller sends "" as null.
func TriggersNote(triggers []Trigger) string {
	if len(triggers) == 0 {
		return ""
	}
	for _, want := range Triggers() {
		found := false
		for _, t := range triggers {
			if t == want {
				found = true
				break
			}
		}
		if !found {
			return TriggersNoteText
		}
	}
	return ""
}
