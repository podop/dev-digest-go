package domain_test

import (
	"testing"

	"github.com/google/go-cmp/cmp"

	"dev-digest-go/backend/internal/ci/domain"
)

func TestBuildPRBody(t *testing.T) {
	want := "Adds the DevDigest review agent `security-reviewer` to this repository's GitHub Actions.\n" +
		"\n" +
		"### Files\n" +
		"- `.devdigest/agents/security-reviewer.yaml`\n" +
		"- `.github/workflows/devdigest-review-security-reviewer.yml`\n" +
		"\n" +
		"### Before merging\n" +
		"1. Add the repository Actions secret `OPENROUTER_API_KEY` (Settings > Secrets and variables > Actions).\n" +
		"   This PR triggers the review workflow on itself, so its check stays red until the secret exists.\n" +
		"2. Merge this PR.\n" +
		"3. To block merges on CRITICAL findings, add the status check `DevDigest Review · security-reviewer` as required in the branch protection of the default branch.\n" +
		"\n" +
		"### Runner\n" +
		"`.devdigest/runner/devdigest-runner-linux-amd64.gz.b64` is the DevDigest CI runner (linux/amd64), built from DevDigest source `0123456789ab`. " +
		"SHA-256 of the decoded binary: `abc123`. The workflow checks it before running.\n" +
		"\n" +
		"Branch: `devdigest/ci`. Generated by DevDigest."
	got := domain.BuildPRBody("security-reviewer",
		[]string{".devdigest/agents/security-reviewer.yaml", ".github/workflows/devdigest-review-security-reviewer.yml"},
		"abc123", "0123456789ab")
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("BuildPRBody() mismatch (-want +got):\n%s", diff)
	}
}
